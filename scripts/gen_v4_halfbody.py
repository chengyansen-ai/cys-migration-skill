def pick_coordinated(pool, usage, k=1):
    """从 pool 中选 k 个最少使用的元素（保证类内多样性）"""
    cand = sorted(set(pool), key=lambda x: usage.get(x, 0))
    chosen = cand[:k]
    for c in chosen:
        usage[c] = usage.get(c, 0) + 1
    return chosen

